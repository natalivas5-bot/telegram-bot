CHANNEL = "t.me/natalyavassileva"

users = {}


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    users[update.effective_user.id] = {
        "step": 0,
        "scores": []
    }
    text = (
        "Привет.\n\n"
        "Ты здесь — значит что-то внутри уже знает.\n"
        "Что пора разобраться.\n\n"
        "Этот тест покажет какой родовой сценарий\n"
        "управляет твоими отношениями.\n\n"
        "10 вопросов.\n"
        "Отвечай честно — первым ощущением.\n"
        "Не думай долго. Тело знает лучше головы.\n\n"
        "Готова? 👇"
    )
    await update.message.reply_text(text)
    await ask_question(update, context)


async def ask_question(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user = users[update.effective_user.id]
    step = user["step"]

    if step >= len(questions):
        await show_result(update, context)
        return

    q = questions[step]
    keyboard = [[a] for a in q["answers"].keys()]
    reply_markup = ReplyKeyboardMarkup(
        keyboard, resize_keyboard=True, one_time_keyboard=True
    )
    num = step + 1
    await update.message.reply_text(
        f"Вопрос {num} из {len(questions)}\n\n{q['text']}",
        reply_markup=reply_markup
    )


async def handle_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    if user_id not in users:
        await start(update, context)
        return

    user = users[user_id]
    step = user["step"]
    answer = update.message.text
    q = questions[step]

    if answer in q["answers"]:
        user["scores"].append(q["answers"][answer])
        user["step"] += 1
        await ask_question(update, context)
    else:
        await update.message.reply_text(
            "Пожалуйста, выбери один из вариантов 👇"
        )


async def show_result(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user = users[update.effective_user.id]
    scores = user["scores"]

    if not scores:
        await update.message.reply_text(
            "Что-то пошло не так. Напиши /start чтобы начать заново."
        )
        return

    total = len(scores)
    counts = {}
    for s in scores:
        counts[s] = counts.get(s, 0) + 1

    sorted_scenarios = sorted(counts.items(), key=lambda x: x[1], reverse=True)
    top_scenarios = sorted_scenarios[:2] if len(sorted_scenarios) > 1 else sorted_scenarios

    result_text = "Твои родовые сценарии:\n\n"

    for scenario_key, count in top_scenarios:
        percent = round(count / total * 100)
        info = scenario_info.get(scenario_key, {})
        name = info.get("name", scenario_key)
        desc = info.get("text", "")
        result_text += f"▪️ {name} — {percent}%\n\n{desc}\n\n"
        result_text += "——————————————\n\n"

    # Первое сообщение — сценарии
    await update.message.reply_text(result_text)

    # Второе сообщение — приглашение на канал
    closing_text = (
        "Эти сценарии — не твоя вина.\n"
        "Не твой характер. Не твоя судьба.\n\n"
        "Они достались тебе по наследству.\n"
        "Без спроса.\n\n"
        "Но теперь ты видишь их.\n"
        "А значит — можешь выбрать.\n\n"
        "Я Наталья. И я помогаю женщинам\n"
        "выйти из этих сценариев.\n"
        "На своём примере знаю — это возможно.\n\n"
        f"Следующий шаг — в моём канале:\n👉 {CHANNEL}"
    )
    await update.message.reply_text(closing_text)


app = ApplicationBuilder().token(TOKEN).build()
app.add_handler(CommandHandler("start", start))
app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_answer))

print("Бот запущен")
app.run_polling()