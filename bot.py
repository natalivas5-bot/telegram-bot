async def start_test(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    user_id = query.from_user.id
    user_data[user_id] = {"question": 0, "scores": [0] * 10}
    await send_question(query, user_id)


async def send_question(query, user_id):
    data = get_user_data(user_id)
    question_number = data["question"]
    if question_number >= len(QUESTIONS):
        await show_result(query, user_id)
        return
    question = QUESTIONS[question_number]
    keyboard = [
        [InlineKeyboardButton(answer, callback_data=f"answer_{scenario}")]
        for answer, scenario in question["answers"]
    ]
    await query.edit_message_text(
        f"*Вопрос {question_number + 1} из {len(QUESTIONS)}*\n\n{question['text']}",
        parse_mode="Markdown",
        reply_markup=InlineKeyboardMarkup(keyboard)
    )


async def answer_question(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    user_id = query.from_user.id
    data = get_user_data(user_id)
    scenario = int(query.data.split("_")[1])
    data["scores"][scenario] += 1
    data["question"] += 1
    await send_question(query, user_id)


async def show_result(query, user_id):
    data = get_user_data(user_id)
    scores = data["scores"]
    scenario = scores.index(max(scores))
    result = SCENARIOS[scenario]
    keyboard = [
        [InlineKeyboardButton("🌿 Посмотреть продолжение", url=CHANNEL_URL)],
        [InlineKeyboardButton("🔄 Пройти тест ещё раз", callback_data="restart")]
    ]
    await query.edit_message_text(
        f"✨ *ТВОЙ РЕЗУЛЬТАТ*\n\n{result['title']}\n\n{result['text']}\n\n"
        "━━━━━━━━━━━━━━\n\n"
        "*Но самое интересное начинается именно здесь.*\n\n"
        "Этот тест показывает один возможный сценарий, который мог стать привычным способом реагировать на жизнь.\n\n"
        "Я подготовила для тебя продолжение — PDF с подробным разбором сценария и практику.\n\n"
        "👇 Если чувствуешь, что этот результат попал в тебя — продолжение ждёт тебя в моём Telegram-канале.",
        parse_mode="Markdown",
        reply_markup=InlineKeyboardMarkup(keyboard)
    )


async def restart(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    user_id = query.from_user.id
    user_data[user_id] = {"question": 0, "scores": [0] * 10}
    await send_question(query, user_id)


def main():
    application = Application.builder().token(BOT_TOKEN).build()
    application.add_handler(CommandHandler("start", start))
    application.add_handler(CallbackQueryHandler(start_test, pattern="^start_test$"))
    application.add_handler(CallbackQueryHandler(answer_question, pattern="^answer_"))
    application.add_handler(CallbackQueryHandler(restart, pattern="^restart$"))
    print("Бот запущен...")
    application.run_polling()


if __name__ == "__main__":
    main()